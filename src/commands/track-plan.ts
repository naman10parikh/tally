/**
 * tally track-plan — THE acceptance test (leg 1). J1 · O1/O2 · BTS-1.
 *
 * Read a product brief / codebase → propose a CANONICAL machine-readable event
 * registry (typed, snake_cased, dedup ledger) + generate typed accessors + EMIT A
 * CI CHECK SCRIPT that FAILS the build on an unregistered / case-variant /
 * type-mutated event. The failing CI check must EXIST as an artifact, not be
 * described (Karpathy Goal-Driven: "done" = the gate fails on a planted variant).
 *
 * No `any`, named exports only. < 400 lines.
 */

