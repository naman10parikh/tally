/** Options for `tally track-plan`. */
export interface TrackPlanOptions {
  app?: string;
  out?: string;
  json: boolean;
}

/** Infer a PropType from a discovered runtime value. */
function inferType(value: unknown): PropType {
  if (typeof value === "number") return "number";
  if (typeof value === "boolean") return "boolean";
  if (typeof value === "string" && !Number.isNaN(Date.parse(value)) && /\d{4}-\d\d-\d\d/.test(value)) {
    return "timestamp";
  }
  return "string";
}

/** Property keys that should ALWAYS be `$set_once` (acquisition/first-touch, O3). */
const ACQUISITION_KEYS = /^(referral_source|referrer|utm_|first_|initial_|acquisition|signup_source|landing)/i;

/**
 * Build a canonical registry from discovered events: collapse case/format
 * variants to one snake_case canonical (BTS-1 merge-don't-rename), union their
 * props, type-infer, and tag acquisition props as `$set_once`.
 */
export function buildRegistry(discovered: ReturnType<typeof discoverEvents>): Registry {
  const byCanonical = new Map<string, EventSpec>();

  for (const ev of discovered) {
    const canonical = canonicalize(ev.name);
    if (!canonical) continue;
    let spec = byCanonical.get(canonical);
    if (!spec) {
      spec = { name: canonical, props: [], registered: true };
      byCanonical.set(canonical, spec);
    }
    if (ev.props) {
      for (const [pname, pval] of Object.entries(ev.props)) {
        const key = canonicalize(pname);
        if (!key || spec.props.some((p) => p.name === key)) continue;
        const prop: PropSpec = { name: key, type: inferType(pval) };
        if (ACQUISITION_KEYS.test(pname)) prop.identity = "set_once";
        spec.props.push(prop);
      }
    }
  }

  return {
    version: 1,
    casing: "snake_case",
    events: [...byCanonical.values()].sort((a, b) => a.name.localeCompare(b.name)),
  };
}

/** Generate a typed-accessors TS module so call sites can't mistype an event. */
function renderTypedAccessors(reg: Registry, app: string): string {
  const lines: string[] = [
    `// AUTO-GENERATED by \`tally track-plan\` for ${app}. Do not hand-edit.`,
    `// The typed accessor layer: import these instead of raw event strings so a`,
    `// call site cannot mint a case-variant (BTS-1). Regenerate on registry change.`,
    ``,
    `export const EVENTS = {`,
  ];
  for (const ev of reg.events) {
    const propType =
      ev.props.length > 0
        ? `{ ${ev.props.map((p) => `${p.name}: ${tsType(p.type)}`).join("; ")} }`
        : `Record<string, never>`;
    lines.push(`  ${jsKey(ev.name)}: "${ev.name}" as const, // props: ${propType}`);
  }
  lines.push(`} as const;`, ``, `export type EventName = (typeof EVENTS)[keyof typeof EVENTS];`, ``);
  return lines.join("\n");
}

function tsType(t: PropType): string {
  return t === "number" ? "number" : t === "boolean" ? "boolean" : t === "timestamp" ? "string | number" : "string";
}

function jsKey(name: string): string {
  return /^[a-z][a-z0-9_]*$/.test(name) ? name : `"${name}"`;
}

/**
 * The CI-check artifact. A **self-contained** `.mjs` that re-discovers events in a
 * target dir, re-loads the registry, runs the same validation logic, prints
 * violations, and exits NON-ZERO if any exist — so a planted `Checkout Started`
 * next to `checkout_started` FAILS the build (BTS-1 acceptance criterion).
 *
 * PORTABILITY (why this inlines the scanner/validator instead of importing from
 * `tally/dist/...`): this artifact runs in the CUSTOMER'S repo/CI, where `tally`
 * is NOT necessarily an installed dependency. A `import ... from "tally/dist/..."`
 * makes `node ci-check-events.mjs` crash with `ERR_MODULE_NOT_FOUND` in exactly
 * the place the gate is supposed to run — so the check could never fail-on-variant
 * (the P0 deliverable would silently never run). The gate must depend on `node:`
 * builtins ONLY. Lockstep with the core is preserved structurally: `track-plan`
 * is the single generator, so the inlined logic is regenerated (never hand-edited)
 * whenever the registry changes. The two inlined functions below are faithful,
 * minimal ports of `discoverEvents` (EVENT_CALL scan) + `canonicalize`/
 * `validateEvents` from src/registry/*.
 */
function renderCiCheck(registryRelPath: string): string {
  return `#!/usr/bin/env node
// AUTO-GENERATED by \`tally track-plan\`. The taxonomy CI gate (O1/BTS-1):
// re-scans the target dir, validates every event against the registry, and EXITS
// NON-ZERO on an unregistered / case-variant / type-mutated event. This is the
// failing-CI-check ARTIFACT — running it on a planted variant fails the build.
//
// SELF-CONTAINED: depends on node: builtins ONLY, so it runs in a customer repo /
// CI with no \`tally\` install (no ERR_MODULE_NOT_FOUND). Do not hand-edit —
// regenerate via \`tally track-plan\` on any registry change.
//
// Usage: node ci-check-events.mjs [targetDir]   (defaults to cwd)
import { readFileSync, readdirSync, statSync, existsSync } from "node:fs";
import { resolve, dirname, join, extname } from "node:path";
import { fileURLToPath } from "node:url";

// --- inlined scanner (faithful minimal port of src/registry/discover.ts) ---
const CODE_EXTS = new Set([".ts", ".tsx", ".js", ".jsx", ".mjs", ".cjs", ".vue", ".svelte"]);
const SKIP_DIRS = new Set(["node_modules", ".git", "dist", "build", ".next", "coverage"]);
const EVENT_CALL = /\\b(?:capture|track)\\s*\\(\\s*['"\\\`]([^'"\\\`]+)['"\\\`]/g;

function walk(dir, out = []) {
  let entries;
  try { entries = readdirSync(dir); } catch { return out; }
  for (const name of entries) {
    if (SKIP_DIRS.has(name)) continue;
    const full = join(dir, name);
    let st;
    try { st = statSync(full); } catch { continue; }
    if (st.isDirectory()) walk(full, out);
    else if (CODE_EXTS.has(extname(name))) out.push(full);
  }
  return out;
}

function discoverEvents(dir) {
  const out = [];
  for (const planName of ["tracking-plan.json", "events.json"]) {
    const planPath = join(dir, planName);
    if (existsSync(planPath)) {
      try {
        const parsed = JSON.parse(readFileSync(planPath, "utf8"));
        const names = Array.isArray(parsed)
          ? parsed.map((e) => (typeof e === "string" ? e : e && typeof e.name === "string" ? e.name : null)).filter(Boolean)
          : parsed && typeof parsed === "object"
            ? (Array.isArray(parsed.events)
                ? parsed.events.map((e) => (typeof e === "string" ? e : e && e.name)).filter(Boolean)
                : Object.keys(parsed))
            : [];
        for (const name of names) out.push({ name, file: planName, line: 1 });
      } catch { /* malformed plan: skip */ }
    }
  }
  for (const file of walk(dir)) {
    let text;
    try { text = readFileSync(file, "utf8"); } catch { continue; }
    const lines = text.split("\\n");
    for (let i = 0; i < lines.length; i++) {
      EVENT_CALL.lastIndex = 0;
      let m;
      while ((m = EVENT_CALL.exec(lines[i])) !== null) {
        out.push({ name: m[1], file: file.slice(dir.length + 1), line: i + 1 });
      }
    }
  }
  return out;
}

// --- inlined validator (faithful port of canonicalize + validateEvents) ---
function canonicalize(name) {
  return name
    .trim()
    .replace(/([a-z0-9])([A-Z])/g, "$1_$2")
    .replace(/[\\s\\-.]+/g, "_")
    .replace(/[^A-Za-z0-9_]+/g, "")
    .toLowerCase()
    .replace(/_+/g, "_")
    .replace(/^_+|_+$/g, "");
}

function validateEvents(reg, discovered) {
  const byCanonical = new Map();
  for (const ev of reg.events) {
    const key = canonicalize(ev.name);
    const existing = byCanonical.get(key);
    if (existing && existing.name !== ev.name) continue;
    byCanonical.set(key, ev);
  }
  const byExact = new Map(reg.events.map((e) => [e.name, e]));
  const violations = [];
  for (const ev of discovered) {
    const canonical = canonicalize(ev.name);
    const exact = byExact.get(ev.name);
    const canon = byCanonical.get(canonical);
    if (!canon) {
      violations.push({ kind: "unregistered", event: ev.name, message: \`Event "\${ev.name}" is not in the registry — register it (the second engineer cannot bypass the ledger, O2).\` });
      continue;
    }
    if (!exact && canon.name !== ev.name) {
      violations.push({ kind: "case-variant", event: ev.name, canonical: canon.name, message: \`Event "\${ev.name}" is a case/format variant of registered "\${canon.name}" — fix the spelling (casing is a semantic boundary, BTS-1). Do NOT rename the historical stream; alias at query time.\` });
      continue;
    }
  }
  return violations;
}

// --- gate ---
const here = dirname(fileURLToPath(import.meta.url));
const targetDir = process.argv[2] ? resolve(process.argv[2]) : process.cwd();
const registry = JSON.parse(readFileSync(resolve(here, ${JSON.stringify(registryRelPath)}), "utf8"));

const discovered = discoverEvents(targetDir);
const violations = validateEvents(registry, discovered);

if (violations.length > 0) {
  console.error("❌ Tracking-plan CI gate FAILED — " + violations.length + " violation(s):");
  for (const v of violations) console.error("  [" + v.kind + "] " + v.message);
  console.error("\\nThe taxonomy is gated in CI, not a wiki (tally O1). Register the event or fix the casing.");
  process.exit(1);
}
console.log("✅ Tracking-plan CI gate passed (" + discovered.length + " event call-sites, 0 violations).");
process.exit(0);
`;
}

/** Atomic write: write to a temp sibling then rename (chaos-safe, no half-files). */
function atomicWrite(path: string, content: string): void {
  const tmp = `${path}.tmp-${process.pid}`;
  writeFileSync(tmp, content, "utf8");
  renameSync(tmp, path);
}

/** Run `tally track-plan <dir>`. */
export function runTrackPlan(dir: string, opts: TrackPlanOptions): void {
  const run = startRun("track-plan");
  const targetDir = resolve(dir);
  if (!existsSync(targetDir)) {
    run.finish("error", "target dir missing");
    fail(opts.json, `directory not found: ${dir}`);
  }

  const app = opts.app ?? "app";
  const outDir = resolve(opts.out ?? join(targetDir, ".tally-plan"));
  mkdirSync(outDir, { recursive: true });

  run.tool("discover.events");
  const discovered = discoverEvents(targetDir);
  const reg = buildRegistry(discovered);

  const registryPath = join(outDir, "registry.json");
  const accessorsPath = join(outDir, "events.ts");
  const ciCheckPath = join(outDir, "ci-check-events.mjs");

  run.tool("registry.write");
  atomicWrite(registryPath, JSON.stringify(reg, null, 2) + "\n");
  atomicWrite(accessorsPath, renderTypedAccessors(reg, app));
  run.tool("ci-check.write");
  atomicWrite(ciCheckPath, renderCiCheck("registry.json"));

  // Surface any non-canonical names discovered (informational — the registry
  // already canonicalized them; this tells the operator what got merged).
  const merged = discovered.filter((d) => d.name !== canonicalize(d.name) && !isCanonicalName(d.name));

  const result = {
    app,
    registryPath,
    typedAccessors: accessorsPath,
    ciCheckPath,
    events: reg.events.map((e) => ({ name: e.name, props: e.props.length, registered: e.registered })),
    discovered: discovered.length,
    mergedVariants: merged.map((m) => ({ found: m.name, canonical: canonicalize(m.name) })),
    trace: run.trace,
  };

  run.finish("ok");

  if (opts.json) {
    emit(true, result, "");
    return;
  }
  process.stdout.write(chalk.bold(`tally track-plan · ${app}\n`));
  process.stdout.write(`  registry:        ${chalk.cyan(registryPath)} (${reg.events.length} canonical events)\n`);
  process.stdout.write(`  typed accessors: ${chalk.cyan(accessorsPath)}\n`);
  process.stdout.write(`  CI gate:         ${chalk.cyan(ciCheckPath)} ${chalk.dim("(fails build on a case-variant — BTS-1)")}\n`);
  if (merged.length > 0) {
    process.stdout.write(chalk.yellow(`  merged ${merged.length} case/format variant(s) to canonical (aliased, not renamed).\n`));
  }
}
